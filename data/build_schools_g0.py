def interp(anchors, score):
    """根据 分数->位次 锚点表线性插值"""
    pts = sorted(anchors.items(), key=lambda x: -x[0])  # 分数降序
    if score >= pts[0][0]:
        return pts[0][1]
    if score <= pts[-1][0]:
        return pts[-1][1]
    for i in range(len(pts) - 1):
        hi_s, hi_r = pts[i]
        lo_s, lo_r = pts[i + 1]
        if lo_s < score <= hi_s:
            frac = (score - lo_s) / (hi_s - lo_s)
            return int(round(lo_r + frac * (hi_r - lo_r)))
    return pts[-1][1]

def interp_rev(anchors, score):
    """分数升序版本"""
    return interp(anchors, score)

